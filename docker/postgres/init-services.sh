#!/bin/sh
set -eu

: "${POSTGRES_USER:?POSTGRES_USER es obligatorio}"
: "${POSTGRES_DB:?POSTGRES_DB es obligatorio}"
: "${CATALOG_DB_PASSWORD:?CATALOG_DB_PASSWORD es obligatorio}"
: "${ORDERS_DB_PASSWORD:?ORDERS_DB_PASSWORD es obligatorio}"

psql --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set ON_ERROR_STOP=1 <<'SQL'
\getenv catalog_password CATALOG_DB_PASSWORD
\getenv orders_password ORDERS_DB_PASSWORD

CREATE ROLE catalog_app LOGIN PASSWORD :'catalog_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
CREATE ROLE orders_app LOGIN PASSWORD :'orders_password' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT;
REVOKE ALL ON DATABASE pipeline FROM PUBLIC;
GRANT CONNECT ON DATABASE pipeline TO catalog_app, orders_app;
CREATE SCHEMA catalog AUTHORIZATION catalog_app;
CREATE SCHEMA orders AUTHORIZATION orders_app;
REVOKE ALL ON SCHEMA catalog FROM PUBLIC;
REVOKE ALL ON SCHEMA orders FROM PUBLIC;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
SQL

unset CATALOG_DB_PASSWORD ORDERS_DB_PASSWORD
